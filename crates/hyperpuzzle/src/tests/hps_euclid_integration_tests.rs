//! Integration tests for the Euclidean puzzle backend.
//!
//! These tests mostly just exercise the puzzle implementation, which contains
//! test assertions scattered throughout.

use hypuz_core::{Mesh, Puzzle, ScrambleParams, ScrambleType, math::RotDir};
use hypuz_impl_euclid::{NdEuclidPuzzleGeometry, SymmetricTwistSystemComponent};

use crate::{catalog, load_global_catalog};

#[test]
fn test_exercise_hps_euclid() -> eyre::Result {
    load_global_catalog();

    for puzzle_id in [
        // 3D platonic
        "cube_ft(3)",
        "cube_ft(5)",
        "megaminx(1)",
        "megaminx_crystal",
        "radio_2", // TODO: should fail because jumble scrambling isn't implemented yet
        // 4D platonic
        "hypercube_ft(3)",
        // 4D truncations
        "rhombic_dodecahedron_ft_2",
        "hypercube_truncation_test_ft",
    ] {
        println!("Testing {puzzle_id} ...");

        println!("  Building ...");
        let p = catalog().build_blocking::<Puzzle>(&puzzle_id.parse()?)?;

        // Test moves generated by a random scramble
        println!("  Scrambling ...");
        let scrambled = p.new_scrambled(ScrambleParams::new_test_scramble(ScrambleType::Full, ""));
        assert!(scrambled.twists.len() > 50);

        // Test moves generated by gizmos
        println!("  Exercising gizmo twists on scrambled puzzle ...");
        let geom = p.components.get_ref::<NdEuclidPuzzleGeometry>()?;
        for gizmo_face in geom.gizmo_axes.iter_keys() {
            let (_gizmo_name, twists) =
                (geom.get_gizmo_twist)(gizmo_face, None, RotDir::Cw, &*scrambled.state).unwrap();
            for twist in twists {
                scrambled.state.do_twist_dyn(&twist)?;
            }
        }
    }

    Ok(())
}
